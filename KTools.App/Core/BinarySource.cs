namespace KTools_App.Core;

/// <summary>
/// Источник исполняемого файла внешней зависимости (ишью 54).
/// По умолчанию используется встроенный бинарник из bin/,
/// опционально — путь, указанный вручную, или поиск в системном PATH.
/// </summary>
public enum BinarySource
{
    /// <summary>Встроенный бинарник из bin/ (поведение по умолчанию).</summary>
    Builtin = 0,

    /// <summary>Путь к исполняемому файлу, указанный пользователем вручную.</summary>
    Custom = 1,

    /// <summary>Поиск исполняемого файла в системном PATH.</summary>
    SystemPath = 2
}
